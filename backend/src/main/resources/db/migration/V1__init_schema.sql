CREATE TABLE faculties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    CONSTRAINT fk_departments_faculty FOREIGN KEY (faculty_id) REFERENCES faculties(id)
);

CREATE TABLE groups_table (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    CONSTRAINT fk_groups_department FOREIGN KEY (department_id) REFERENCES departments(id)
);

CREATE TABLE disciplines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE teacher_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id BIGINT NOT NULL,
    group_id BIGINT NOT NULL,
    discipline_id BIGINT NOT NULL,
    CONSTRAINT fk_teacher_assignment_group FOREIGN KEY (group_id) REFERENCES groups_table(id),
    CONSTRAINT fk_teacher_assignment_discipline FOREIGN KEY (discipline_id) REFERENCES disciplines(id),
    CONSTRAINT uk_teacher_assignment UNIQUE (teacher_id, group_id, discipline_id)
);

CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    due_date TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    teacher_id BIGINT NOT NULL,
    group_id BIGINT NOT NULL,
    discipline_id BIGINT NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT fk_task_group FOREIGN KEY (group_id) REFERENCES groups_table(id),
    CONSTRAINT fk_task_discipline FOREIGN KEY (discipline_id) REFERENCES disciplines(id)
);

CREATE TABLE submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    submitted_at TIMESTAMP NOT NULL,
    status VARCHAR(32) NOT NULL,
    content TEXT,
    teacher_feedback TEXT,
    revision_count INTEGER NOT NULL DEFAULT 0,
    version_number INTEGER NOT NULL DEFAULT 1,
    awarded_rating INTEGER,
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_submission_task FOREIGN KEY (task_id) REFERENCES tasks(id)
);

CREATE TABLE submission_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT NOT NULL,
    version_number INTEGER NOT NULL,
    submitted_at TIMESTAMP NOT NULL,
    content TEXT,
    teacher_feedback TEXT,
    status VARCHAR(32) NOT NULL,
    CONSTRAINT fk_submission_version_submission FOREIGN KEY (submission_id) REFERENCES submissions(id),
    CONSTRAINT uk_submission_version UNIQUE (submission_id, version_number)
);

CREATE TABLE academic_rating_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    task_id BIGINT NOT NULL,
    rating INTEGER NOT NULL,
    reason VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_rating_task FOREIGN KEY (task_id) REFERENCES tasks(id),
    CONSTRAINT uk_rating_student_task UNIQUE (student_id, task_id)
);
